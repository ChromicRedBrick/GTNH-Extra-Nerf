import pl.kuba6000.gtnhextranerf.audit.AuditScope;

/** Material definitions and their registry audit. GT owns all generated items and fluids. */
public final class NerfMaterials {

    public interface ThreadSafeUnificationHook {
    }

    public static final String FINISHED_TUNGSTEN_STEEL_NAME = "TungTungTungstensteel";
    // Persisted GT metadata: never dynamically allocate or change this number after worlds use the material.
    private static final int RAW_TUNGSTEN_STEEL_ID = 859;
    private static Materials rawTungstenSteel;

    private NerfMaterials() {}

    /** Called by GT's material handler, after built-in IDs are assigned and before forms are generated. */
    public static void register() {
        if (rawTungstenSteel != null || Materials.get("RawTungstenSteel") != Materials._NULL)
            throw new IllegalStateException("Raw tungstensteel is already registered");
        for (Materials existing : Materials.getAll()) if (existing.mMetaItemSubID == RAW_TUNGSTEN_STEEL_ID)
            throw new IllegalStateException("Raw tungstensteel material ID is occupied by " + existing.mName);
        short[] originalColor = Materials.TungstenSteel.mRGBa;
        int originalARGB = originalColor[3] << 24 | originalColor[0] << 16 | originalColor[1] << 8 | originalColor[2];
        rawTungstenSteel = new MaterialBuilder().setName("RawTungstenSteel")
            .setDefaultLocalName("Tungstensteel")
            .setIconSet(TextureSet.SET_METALLIC)
            .setColor(Materials.TungstenSteel.mColor)
            .setARGB(originalARGB)
            .addDustItems()
            .addMetalItems()
            .setMeltingPoint(4000)
            .setBlastFurnaceTemp(4000)
            .setBlastFurnaceRequired(true)
            .setAutoGenerateBlastFurnaceRecipes(false)
            .setAutoGeneratedVacuumFreezerRecipe(false)
            .addMaterial(Materials.Steel, 1)
            .addMaterial(Materials.Tungsten, 1)
            .addSubTag(SubTag.METAL)
            .addSubTag(SubTag.MULTI_PLATE)
            .constructMaterial();
        rawTungstenSteel.mMetaItemSubID = RAW_TUNGSTEN_STEEL_ID;
        rawTungstenSteel.setProcessingMaterialTierEU(Materials.TungstenSteel.getProcessingMaterialTierEU());
        Materials.TungstenSteel.setChemicalFormula("");
    }

    public static Materials rawTungstenSteel() {
        return Objects.requireNonNull(rawTungstenSteel, "Raw tungstensteel has not been registered");
    }

    public static void registerBlocks() {
        new BlockMetal(
            "raw_tungstensteel_block",
            new Materials[] { rawTungstenSteel() },
            OrePrefixes.block,
            new IIconContainer[] { Textures.BlockIcons.BLOCK_STEEL }) {

            @Override
            @SideOnly(Side.CLIENT)
            public void getSubBlocks(Item item, CreativeTabs tab, List<ItemStack> stacks) {
                stacks.add(new ItemStack(item, 1, 0));
            }
        };
    }

    public static void verify() {
        AuditManager.run(AuditScope.VERIFY_BRAINROT_MATERIALS, audit -> {
            if (!ThreadSafeUnificationHook.class.isAssignableFrom(GTOreDictUnificator.class))
                throw new IllegalStateException("Thread-safe GT unification lookup hook is missing");
            Materials raw = rawTungstenSteel(), finished = Materials.TungstenSteel;
            if (Materials.get("RawTungstenSteel") != raw || raw.mMaterialInto != raw
                || GregTechAPI.sGeneratedMaterials[RAW_TUNGSTEN_STEEL_ID] != raw
                || finished.mMetaItemSubID != 316
                || !"TungstenSteel".equals(finished.mName)
                || !FINISHED_TUNGSTEN_STEEL_NAME.equals(finished.mDefaultLocalName)
                || !finished.getChemicalFormula()
                    .isEmpty()
                || !Arrays.equals(raw.mRGBa, finished.mRGBa)
                || !"Tungstensteel".equals(raw.mDefaultLocalName))
                throw new IllegalStateException("Brainrot material identities or names are invalid");
            for (OrePrefixes prefix : new OrePrefixes[] { OrePrefixes.dust, OrePrefixes.ingot, OrePrefixes.ingotHot,
                OrePrefixes.plate, OrePrefixes.plateDouble, OrePrefixes.block }) {
                ItemStack rawItem = GTOreDictUnificator.get(prefix, raw, 1);
                ItemStack finishedItem = GTOreDictUnificator.get(prefix, finished, 1);
                if (rawItem == null || finishedItem == null
                    || rawItem.isItemEqual(finishedItem)
                    || OreDictionary.getOres(
                        prefix.get(finished)
                            .toString())
                        .stream()
                        .anyMatch(rawItem::isItemEqual))
                    throw new IllegalStateException("Missing or unified brainrot material form: " + prefix);
            }
            if (raw.getMolten(1) == null || finished.getMolten(1) == null
                || raw.getMolten(1)
                    .isFluidEqual(finished.getMolten(1))
                || FluidRegistry.getFluid("molten.tungstensteel") != finished.getMolten(1)
                    .getFluid())
                throw new IllegalStateException("Brainrot molten identities are invalid");
            audit.success();
        });
    }
}
